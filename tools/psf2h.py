#!/usr/bin/env python3
"""Convert PSF1/PSF2 console fonts (ASCII 32..126) into one C header.

  psf2h.py name=font.psf[.gz] [name=font.psf[.gz] ...] > fonts.h

Each font becomes `static const font_t FONT_<NAME>` (see the typedef in the output). Glyph rows are
packed MSB first, ceil(w/8) bytes per row, 95 glyphs back to back.
"""
import gzip, struct, sys


def load(path):
    data = gzip.open(path).read() if path.endswith(".gz") else open(path, "rb").read()
    if data[:2] == b"\x36\x04":                     # PSF1: always 8 px wide
        cs = data[3]
        return data, 4, 8, cs, cs
    if data[:4] == b"\x72\xb5\x4a\x86":             # PSF2
        _, _, hdr, _, _n, cs, h, w = struct.unpack("<8I", data[:32])
        return data, hdr, w, h, cs
    sys.exit(f"{path}: not a PSF font")


print("""/* Generated by tools/gen-fonts.sh (tools/psf2h.py) from the Terminus font
 * (https://terminus-font.sourceforge.net/, Copyright (c) 2020 Dimitar Toshkov Zhekov,
 * SIL Open Font License 1.1, see LICENSE). ASCII 32..126 only. Do not edit. */
#ifndef FONTS_H
#define FONTS_H
typedef struct { int w, h, stride; const unsigned char *data; } font_t;   /* data: 95 glyphs */
""")
names = []
for arg in sys.argv[1:]:
    name, path = arg.split("=", 1)
    data, off, w, h, cs = load(path)
    stride = (w + 7) // 8
    assert cs == h * stride, f"{path}: unexpected glyph size"
    print(f"/* {w}x{h} */")
    print(f"static const unsigned char font_{name}_data[95 * {cs}] = {{")
    for c in range(32, 127):
        row = data[off + c * cs: off + (c + 1) * cs]
        print("\t" + ",".join(f"0x{b:02x}" for b in row) + ",")
    print("};")
    print(f"static const font_t FONT_{name.upper()} = {{ {w}, {h}, {stride}, font_{name}_data }};\n")
print("#endif")
